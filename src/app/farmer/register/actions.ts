'use server';

import { randomUUID } from 'crypto';
import { createClient } from '../../../lib/supabase/server';

type FarmerDocumentBucket =
  | 'farmer-photos'
  | 'farmer-aadhaar'
  | 'farmer-bank-documents';

type UploadAuthorization =
  | { path: string; token: string }
  | { error: string };

type VerificationResult =
  | { path: string }
  | { error: string };

function isAllowedBucket(bucket: string): bucket is FarmerDocumentBucket {
  return bucket === 'farmer-photos' ||
    bucket === 'farmer-aadhaar' ||
    bucket === 'farmer-bank-documents';
}

function allowedTypesFor(bucket: FarmerDocumentBucket) {
  return bucket === 'farmer-photos'
    ? ['image/jpeg', 'image/png', 'image/webp']
    : ['image/jpeg', 'image/png', 'image/webp', 'application/pdf'];
}

function hasSignature(bytes: Uint8Array, mimeType: string) {
  if (mimeType === 'image/jpeg') {
    return bytes.length >= 3 &&
      bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff;
  }

  if (mimeType === 'image/png') {
    return bytes.length >= 8 &&
      bytes[0] === 0x89 && bytes[1] === 0x50 &&
      bytes[2] === 0x4e && bytes[3] === 0x47 &&
      bytes[4] === 0x0d && bytes[5] === 0x0a &&
      bytes[6] === 0x1a && bytes[7] === 0x0a;
  }

  if (mimeType === 'image/webp') {
    return bytes.length >= 12 &&
      String.fromCharCode(bytes[0], bytes[1], bytes[2], bytes[3]) === 'RIFF' &&
      String.fromCharCode(bytes[8], bytes[9], bytes[10], bytes[11]) === 'WEBP';
  }

  if (mimeType === 'application/pdf') {
    return bytes.length >= 5 &&
      String.fromCharCode(bytes[0], bytes[1], bytes[2], bytes[3], bytes[4]) === '%PDF-';
  }

  return false;
}

/**
 * Creates a short-lived signed upload authorization. The browser uploads
 * directly to Supabase Storage, avoiding Vercel Server Action body limits.
 * The authenticated storage INSERT policy still restricts the object path
 * to the current user's folder.
 */
export async function createFarmerApplicationDocumentUpload(
  bucketValue: string,
  fileSize: number,
  contentType: string
): Promise<UploadAuthorization> {
  if (!isAllowedBucket(bucketValue)) {
    return { error: 'Unsupported document category.' };
  }

  const bucket = bucketValue;
  const isPhoto = bucket === 'farmer-photos';
  const maxBytes = isPhoto ? 5 * 1024 * 1024 : 10 * 1024 * 1024;

  if (!Number.isFinite(fileSize) || fileSize <= 0 || fileSize > maxBytes) {
    return {
      error: `File size must be greater than zero and no more than ${isPhoto ? '5 MB' : '10 MB'}.`,
    };
  }

  if (!allowedTypesFor(bucket).includes(contentType)) {
    return { error: 'Unsupported file format for this document category.' };
  }

  const supabase = createClient();
  const {
    data: { user },
    error: authError,
  } = await supabase.auth.getUser();

  if (authError || !user) {
    return { error: 'Please sign in before uploading farmer documents.' };
  }

  const extensionByType: Record<string, string> = {
    'image/jpeg': 'jpg',
    'image/png': 'png',
    'image/webp': 'webp',
    'application/pdf': 'pdf',
  };
  const path = `${user.id}/${randomUUID()}.${extensionByType[contentType]}`;

  const { data, error } = await supabase.storage
    .from(bucket)
    .createSignedUploadUrl(path, { upsert: false });

  if (error || !data?.token) {
    return { error: 'Unable to authorize a secure document upload.' };
  }

  return { path, token: data.token };
}

/**
 * Verify the bytes after the direct Storage upload. A client-provided MIME
 * type is not trusted until the downloaded object's signature is checked.
 */
export async function verifyFarmerApplicationDocument(
  bucketValue: string,
  path: string,
  contentType: string
): Promise<VerificationResult> {
  if (!isAllowedBucket(bucketValue)) {
    return { error: 'Unsupported document category.' };
  }

  const bucket = bucketValue;
  if (!allowedTypesFor(bucket).includes(contentType)) {
    return { error: 'Unsupported file format for this document category.' };
  }

  const supabase = createClient();
  const {
    data: { user },
    error: authError,
  } = await supabase.auth.getUser();

  if (authError || !user) {
    return { error: 'Please sign in to verify the uploaded document.' };
  }

  // Object paths are generated by the server; reject path traversal and
  // prevent a caller from asking the server to inspect another user's file.
  if (
    !path.startsWith(`${user.id}/`) ||
    path.includes('..') ||
    path.startsWith('/') ||
    path.includes('\\')
  ) {
    return { error: 'Invalid document path.' };
  }

  const { data: file, error: downloadError } = await supabase.storage
    .from(bucket)
    .download(path);

  if (downloadError || !file) {
    return { error: 'Unable to verify the uploaded document.' };
  }

  const bytes = new Uint8Array(await file.arrayBuffer());
  if (!hasSignature(bytes, contentType)) {
    await supabase.storage.from(bucket).remove([path]);
    return { error: 'The uploaded file content does not match its declared file type.' };
  }

  return { path };
}

/**
 * Remove only the current applicant's uploaded objects that are not linked
 * to an application. Storage RLS enforces this condition as a second layer.
 */
export async function cleanupUnlinkedFarmerApplicationDocuments(
  documents: { bucket: string; path: string }[]
): Promise<void> {
  const supabase = createClient();
  const {
    data: { user },
    error: authError,
  } = await supabase.auth.getUser();

  if (authError || !user || !Array.isArray(documents)) return;

  const allowedBuckets: FarmerDocumentBucket[] = [
    'farmer-photos',
    'farmer-aadhaar',
    'farmer-bank-documents',
  ];

  for (const bucket of allowedBuckets) {
    const paths = documents
      .filter((item) =>
        item &&
        item.bucket === bucket &&
        typeof item.path === 'string' &&
        item.path.startsWith(`${user.id}/`) &&
        !item.path.includes('..') &&
        !item.path.includes('\\')
      )
      .map((item) => item.path);

    if (paths.length > 0) {
      // The storage DELETE policy allows only unlinked files in this user's
      // folder; linked application documents are intentionally immutable here.
      await supabase.storage.from(bucket).remove(paths);
    }
  }
}
